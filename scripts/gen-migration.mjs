// Phase 8 — generate the content-migration SQL (existing JSON/content → Supabase)
// AND a keymap that lets the public loaders reconstruct the exact original JSON
// keys (which mix snake_case and camelCase, e.g. hero_leadBefore_id) from the
// snake_case DB columns. Prints SQL to stdout; writes keymap to
// src/lib/content/_keymap.json.
//
// Run: node scripts/gen-migration.mjs > /tmp/migration.sql
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve('.');
const readJSON = (p) => JSON.parse(fs.readFileSync(path.join(ROOT, p), 'utf8'));
const readDir = (d) => fs.readdirSync(path.join(ROOT, d)).filter((f) => f.endsWith('.json')).sort();

const camelToSnake = (k) => k.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/([A-Z])([A-Z][a-z])/g, '$1_$2').toLowerCase();
const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const jb = (v) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
const slugify = (s) => String(s).toLowerCase().normalize('NFKD').replace(/[̀-ͯ]/g, '')
  .replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 80);

const keymap = {}; // { table: { snake_col: originalKey } }
let sql = '-- AUTO-GENERATED by scripts/gen-migration.mjs — content migration (published)\n\n';

// A few table columns were named differently than the source JSON key.
const OVERRIDE = { about: { prin_items: 'principles', bound_items: 'boundaries' } };

// ---- singletons (id = 1): explode object into snake_case columns ----------
function singleton(table, obj) {
  keymap[table] = {};
  const cols = [], vals = [];
  for (const [k, v] of Object.entries(obj)) {
    const col = OVERRIDE[table]?.[k] ?? camelToSnake(k);
    keymap[table][col] = k;
    cols.push(col);
    vals.push(Array.isArray(v) || (v && typeof v === 'object') ? jb(v) : q(v));
  }
  sql += `delete from ${table};\n`;
  sql += `insert into ${table} (id, ${cols.join(', ')}) values (1, ${vals.join(', ')});\n\n`;
}

singleton('homepage', readJSON('src/data/home.json'));
singleton('about', readJSON('src/data/about.json'));
singleton('pricing', readJSON('src/data/pricing.json'));

// site_settings (subset of columns exist; keep matching ones)
{
  const s = readJSON('src/data/settings.json');
  keymap['site_settings'] = {};
  const cols = [], vals = [];
  for (const [k, v] of Object.entries(s)) {
    const col = camelToSnake(k);
    keymap['site_settings'][col] = k;
    cols.push(col); vals.push(q(v));
  }
  sql += `delete from site_settings;\n`;
  sql += `insert into site_settings (id, ${cols.join(', ')}) values (1, ${vals.join(', ')});\n\n`;
}

// ---- seo_settings: one row per page_key -----------------------------------
{
  keymap['seo_settings'] = { title_id: 'title_id', title_en: 'title_en', desc_id: 'desc_id', desc_en: 'desc_en', og_image: 'ogImage' };
  sql += `delete from seo_settings;\n`;
  for (const f of readDir('src/data/seo')) {
    const pk = f.replace(/\.json$/, '');
    const o = readJSON(`src/data/seo/${f}`);
    sql += `insert into seo_settings (page_key, title_id, title_en, desc_id, desc_en, og_image) values (${q(pk)}, ${q(o.title_id)}, ${q(o.title_en)}, ${q(o.desc_id)}, ${q(o.desc_en)}, ${q(o.ogImage)});\n`;
  }
  sql += '\n';
}

// ---- services collection --------------------------------------------------
{
  sql += `delete from services;\n`;
  for (const f of readDir('src/content/services')) {
    const o = readJSON(`src/content/services/${f}`);
    sql += `insert into services (display_order, slug_id, slug_en, n_id, n_en, h_id, h_en, p_id, p_en, meta_id, meta_en, status) values (${o.order}, ${q(o.slug_id)}, ${q(o.slug_en)}, ${q(o.n_id)}, ${q(o.n_en)}, ${q(o.h_id)}, ${q(o.h_en)}, ${q(o.p_id)}, ${q(o.p_en)}, ${q(o.meta_id)}, ${q(o.meta_en)}, 'published');\n`;
  }
  sql += '\n';
}

// ---- stats collection -----------------------------------------------------
{
  const st = readJSON('src/data/stats.json');
  sql += `delete from stats;\n`;
  st.items.forEach((it, i) => {
    sql += `insert into stats (display_order, num, suffix, label_id, label_en, desc_id, desc_en) values (${i + 1}, ${q(it.num)}, ${q(it.suffix)}, ${q(it.label_id)}, ${q(it.label_en)}, ${q(it.desc_id)}, ${q(it.desc_en)});\n`;
  });
  sql += '\n';
}

// ---- projects collection (explicit mapping; slug from name) ----------------
{
  sql += `delete from projects;\n`;
  const seen = new Set();
  for (const f of readDir('src/content/projects')) {
    const o = readJSON(`src/content/projects/${f}`);
    let slug = slugify(o.name);
    while (seen.has(slug)) slug += '-x';
    seen.add(slug);
    const cols = ['title', 'slug', 'project_url', 'cover_image', 'cover_alt_id', 'cover_alt_en',
      'short_description_id', 'short_description_en', 'description_id', 'description_en',
      'tags', 'featured', 'display_order', 'status', 'published_at'];
    const vals = [q(o.name), q(slug), q(o.url), q(o.image), q(o.alt_id), q(o.alt_en),
      q(o.desc_id), q(o.desc_en), q(o.desc_id), q(o.desc_en),
      `array[${(o.tags || []).map(q).join(',')}]::text[]`, o.featured ? 'true' : 'false',
      o.order, `'published'`, 'now()'];
    sql += `insert into projects (${cols.join(', ')}) values (${vals.join(', ')});\n`;
  }
  sql += '\n';
}

fs.mkdirSync(path.join(ROOT, 'src/lib/content'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'src/lib/content/_keymap.json'), JSON.stringify(keymap, null, 2));
process.stdout.write(sql);
